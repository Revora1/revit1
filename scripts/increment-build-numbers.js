import fs from 'fs';
import path from 'path';

const rootDir = process.cwd();

console.log('[Auto-Increment] Starting build number incrementation...');

const offset = 200; // Base offset to keep versions higher than previous
const githubRunNumber = process.env.GITHUB_RUN_NUMBER ? parseInt(process.env.GITHUB_RUN_NUMBER, 10) : null;

// Read and increment package.json version
const packageJsonPath = path.join(rootDir, 'package.json');
let packageVersion = '1.0.0';
try {
  const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
  const currentVersion = packageJson.version || '1.0.0';
  const versionParts = currentVersion.split('.');
  
  if (versionParts.length === 3) {
    let patch = parseInt(versionParts[2], 10);
    
    if (githubRunNumber !== null) {
      patch = offset + githubRunNumber;
    } else if (!isNaN(patch)) {
      patch += 1;
    }
    
    if (!isNaN(patch)) {
      versionParts[2] = patch.toString();
      packageVersion = versionParts.join('.');
    } else {
      packageVersion = currentVersion;
    }
  } else {
    packageVersion = currentVersion;
  }
  
  packageJson.version = packageVersion;
  fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2) + '\n', 'utf8');
  console.log(`[Auto-Increment] package.json version updated to ${packageVersion}`);
} catch (e) {
  console.error('[Auto-Increment] Failed to read or update package.json version:', e);
}

let androidBuildNum = 1;
let iosBuildNum = 1;

// If we have a GitHub run number, use it directly for native build numbers
if (githubRunNumber !== null) {
  androidBuildNum = offset + githubRunNumber;
  iosBuildNum = offset + githubRunNumber;
}

// 1. Android build.gradle
const androidGradlePath = path.join(rootDir, 'android/app/build.gradle');
if (fs.existsSync(androidGradlePath)) {
  let content = fs.readFileSync(androidGradlePath, 'utf8');
  const match = content.match(/versionCode\s*=\s*(\d+)/);
  if (match) {
    const currentCode = parseInt(match[1], 10);
    if (githubRunNumber === null) {
      androidBuildNum = currentCode + 1;
    }
    content = content.replace(/versionCode\s*=\s*\d+/, `versionCode = ${androidBuildNum}`);
    console.log(`[Auto-Increment] Android versionCode updated to ${androidBuildNum}`);
  } else {
    console.warn('[Auto-Increment] Android versionCode not found in build.gradle');
  }
  
  // Also sync versionName to match package.json version
  if (content.match(/versionName\s*=\s*"[^"]*"/)) {
    content = content.replace(/versionName\s*=\s*"[^"]*"/, `versionName = "${packageVersion}"`);
    console.log(`[Auto-Increment] Android versionName updated to ${packageVersion}`);
  }
  
  fs.writeFileSync(androidGradlePath, content, 'utf8');
} else {
  console.warn('[Auto-Increment] Android build.gradle not found');
}

// 2. iOS project.pbxproj
const iosProjPath = path.join(rootDir, 'ios/App/App.xcodeproj/project.pbxproj');
if (fs.existsSync(iosProjPath)) {
  let content = fs.readFileSync(iosProjPath, 'utf8');
  const matches = content.match(/CURRENT_PROJECT_VERSION\s*=\s*(\d+);/g);
  if (matches) {
    const singleMatch = content.match(/CURRENT_PROJECT_VERSION\s*=\s*(\d+);/);
    const currentVersion = parseInt(singleMatch[1], 10);
    if (githubRunNumber === null) {
      iosBuildNum = currentVersion + 1;
    }
    content = content.replace(/CURRENT_PROJECT_VERSION\s*=\s*\d+;/g, `CURRENT_PROJECT_VERSION = ${iosBuildNum};`);
    console.log(`[Auto-Increment] iOS CURRENT_PROJECT_VERSION updated to ${iosBuildNum}`);
  } else {
    console.warn('[Auto-Increment] iOS CURRENT_PROJECT_VERSION not found in project.pbxproj');
  }

  // Also sync MARKETING_VERSION to match package.json version
  if (content.match(/MARKETING_VERSION\s*=\s*[^;]+;/)) {
    content = content.replace(/MARKETING_VERSION\s*=\s*[^;]+;/g, `MARKETING_VERSION = ${packageVersion};`);
    console.log(`[Auto-Increment] iOS MARKETING_VERSION updated to ${packageVersion}`);
  }

  fs.writeFileSync(iosProjPath, content, 'utf8');
} else {
  console.warn('[Auto-Increment] iOS project.pbxproj not found');
}

// 3. Write src/version.ts for the React app
const versionTsPath = path.join(rootDir, 'src/version.ts');
const versionTsContent = `// This file is auto-generated by scripts/increment-build-numbers.js. Do not edit.
export const VERSION_INFO = {
  version: "${packageVersion}",
  androidBuild: ${androidBuildNum},
  iosBuild: ${iosBuildNum}
};
`;

try {
  fs.writeFileSync(versionTsPath, versionTsContent, 'utf8');
  console.log(`[Auto-Increment] Wrote src/version.ts with Version ${packageVersion} (Android: ${androidBuildNum}, iOS: ${iosBuildNum})`);
} catch (e) {
  console.error('[Auto-Increment] Failed to write src/version.ts:', e);
}
